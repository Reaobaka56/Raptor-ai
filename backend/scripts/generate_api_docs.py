"""Regenerate docs/API.md from the live FastAPI route table.

    cd backend && python -m scripts.generate_api_docs > ../docs/API.md

Auth is inferred from each route's dependencies, so the table can't drift from the code.
"""
import os
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from fastapi.routing import APIRoute  # noqa: E402

from app.main import app  # noqa: E402


def auth_of(route: APIRoute) -> str:
    names = {getattr(d.call, "__name__", "") for d in route.dependant.dependencies}
    if "get_required_github_session" in names:
        return "required"
    if "get_optional_github_session" in names:
        return "optional"
    return "public"


def iter_routes(routes, prefix=""):
    """Flatten the route tree. Newer FastAPI wraps include_router() results in
    lazy _IncludedRouter objects; older versions flatten them already."""
    for r in routes:
        if isinstance(r, APIRoute):
            yield r
        elif hasattr(r, "original_router"):
            ctx = getattr(r, "include_context", None)
            yield from iter_routes(r.original_router.routes, prefix + (getattr(ctx, "prefix", "") or ""))


def main() -> None:
    groups = defaultdict(list)
    for r in iter_routes(app.routes):
        if not isinstance(r, APIRoute) or r.path.startswith(("/docs", "/openapi", "/redoc")):
            continue
        parts = [p for p in r.path.split("/") if p]
        key = "/".join(parts[:2]) if parts and parts[0] == "api" and len(parts) > 1 else (parts[0] if parts else "/")
        for m in sorted(r.methods - {"HEAD", "OPTIONS"}):
            groups[key].append((r.path, m, auth_of(r), (r.summary or r.name or "").replace("_", " ")))

    print("# API reference\n")
    print("> Generated by `backend/scripts/generate_api_docs.py` from the live route table - do not edit by hand.")
    print("> Interactive docs: `/docs` (Swagger UI) on a running backend.\n")
    print("**Auth**: `required` = valid session cookie / bearer token; `optional` = works logged out with reduced data; `public` = open (still rate limited).\n")
    for key in sorted(groups):
        print(f"## `/{key}`\n")
        print("| Method | Path | Auth | Handler |")
        print("|---|---|---|---|")
        for path, method, auth, name in sorted(groups[key]):
            print(f"| {method} | `{path}` | {auth} | {name} |")
        print()


if __name__ == "__main__":
    main()
